-- ---------------------------------------------------------------------------
-- Constraints / FKs (skip if they already exist)
-- ---------------------------------------------------------------------------

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'shelves_user_id_fkey'
  ) then
    alter table public.shelves
      add constraint shelves_user_id_fkey
      foreign key (user_id) references auth.users (id) on delete cascade;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'shelves_library_id_fkey'
  ) then
    alter table public.shelves
      add constraint shelves_library_id_fkey
      foreign key (library_id) references public.libraries (id) on delete set null;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'user_books_user_id_fkey'
  ) then
    alter table public.user_books
      add constraint user_books_user_id_fkey
      foreign key (user_id) references auth.users (id) on delete cascade;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'user_books_shelf_id_fkey'
  ) then
    alter table public.user_books
      add constraint user_books_shelf_id_fkey
      foreign key (shelf_id) references public.shelves (id) on delete cascade;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'libraries_user_id_fkey'
  ) then
    alter table public.libraries
      add constraint libraries_user_id_fkey
      foreign key (user_id) references auth.users (id) on delete cascade;
  end if;
end $$;

-- Unique image_url (required by the app). Fails if duplicates already exist.
