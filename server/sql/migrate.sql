create unique index if not exists library_shares_token_key on public.library_shares (token);

-- ---------------------------------------------------------------------------
-- Grants + RLS
-- ---------------------------------------------------------------------------

grant usage on schema public to anon, authenticated, service_role;

grant select, insert, update, delete
  on public.libraries, public.shelves, public.user_books, public.library_shares
  to authenticated;

grant all on public.libraries, public.shelves, public.user_books, public.ocr_cache, public.library_shares
  to service_role;

revoke all on public.ocr_cache from anon, authenticated;

grant usage, select
  on all sequences in schema public
  to authenticated, service_role;

alter table public.libraries enable row level security;
alter table public.shelves enable row level security;
alter table public.user_books enable row level security;
alter table public.ocr_cache enable row level security;
alter table public.library_shares enable row level security;

drop policy if exists libraries_own_rows on public.libraries;
create policy libraries_own_rows
  on public.libraries
  for all
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists shelves_own_rows on public.shelves;
create policy shelves_own_rows
  on public.shelves
  for all
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists user_books_own_rows on public.user_books;
create policy user_books_own_rows
  on public.user_books
  for all
  to authenticated
  using (auth.uid() = user_id)
  with check (
    auth.uid() = user_id
    and (
      shelf_id is null
      or exists (
        select 1
        from public.shelves s
        where s.id = shelf_id
          and s.user_id = auth.uid()
      )
    )
  );

drop policy if exists library_shares_own_rows on public.library_shares;
create policy library_shares_own_rows
  on public.library_shares
  for all
  to authenticated
  using (auth.uid() = user_id)
  with check (
    auth.uid() = user_id
    and (
      library_id is null
      or exists (
        select 1
        from public.libraries l
        where l.id = library_id
          and l.user_id = auth.uid()
      )
    )
  );

-- ---------------------------------------------------------------------------
-- Storage bucket
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public)
values ('shelves', 'shelves', false)
on conflict (id) do update
set public = false;

drop policy if exists "Public read shelf images" on storage.objects;
drop policy if exists "Users read own shelf images" on storage.objects;
create policy "Users read own shelf images"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'shelves'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "Users upload own shelf images" on storage.objects;
create policy "Users upload own shelf images"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'shelves'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "Users update own shelf images" on storage.objects;
create policy "Users update own shelf images"
  on storage.objects
  for update
  to authenticated
  using (
    bucket_id = 'shelves'
    and (storage.foldername(name))[1] = auth.uid()::text
  )
  with check (
    bucket_id = 'shelves'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "Users delete own shelf images" on storage.objects;
create policy "Users delete own shelf images"
  on storage.objects
  for delete
  to authenticated
  using (
    bucket_id = 'shelves'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

