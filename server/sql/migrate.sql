-- ---------------------------------------------------------------------------
-- user_books: cover_url -> cover, then add remaining columns
-- ---------------------------------------------------------------------------

do $$
begin
  if public.hilibrary_has_column('user_books', 'cover_url')
     and not public.hilibrary_has_column('user_books', 'cover') then
    alter table public.user_books rename column cover_url to cover;
  elsif public.hilibrary_has_column('user_books', 'cover_url')
        and public.hilibrary_has_column('user_books', 'cover') then
    update public.user_books
    set cover = cover_url
    where cover is null and cover_url is not null;
  end if;
end $$;

